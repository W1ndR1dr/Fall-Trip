// Refresh live conditions baked into the app (run ~Wed Oct 7, then again
// Friday morning if you like). Writes src/content/conditions.js.
//   node scripts/update-conditions.mjs
// Sources: NWS API (api.weather.gov), NPS Yosemite conditions page, Caltrans
// road-conditions text. The fall color report is prose, so it's updated by
// hand in src/content/trip.js (see UPDATE.md).
import { writeFile } from 'node:fs/promises';

const UA = { 'User-Agent': 'FallTrip family trip app (personal, non-commercial)', Accept: 'application/geo+json, text/html' };
const out = new URL('../src/content/conditions.js', import.meta.url);

const PLACES = [
  ['Mammoth Lakes', 37.6485, -118.9721],
  ['June Lake', 37.7802, -119.0746],
  ['Lee Vining', 37.9577, -119.121],
  ['Tioga Pass', 37.9107, -119.2577],
  ['Bishop', 37.3635, -118.3951],
];
const TRIP_DAYS = ['2026-10-09', '2026-10-10', '2026-10-11'];

async function get(url, as = 'json') {
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return as === 'json' ? r.json() : r.text();
}

const strip = (html) => html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;|&#160;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

async function forecast([name, lat, lon]) {
  const pt = await get(`https://api.weather.gov/points/${lat},${lon}`);
  const fc = await get(pt.properties.forecast);
  const periods = fc.properties.periods;
  const onTrip = periods.filter((p) => TRIP_DAYS.some((d) => p.startTime.startsWith(d)));
  const use = (onTrip.length ? onTrip : periods.slice(0, 6)).map((p) => ({
    name: p.name,
    temp: `${p.temperature}°${p.temperatureUnit}`,
    wind: `${p.windSpeed} ${p.windDirection}`.trim(),
    text: p.shortForecast,
    detail: p.detailedForecast,
  }));
  return { place: name, onTrip: onTrip.length > 0, updated: fc.properties.updateTime || fc.properties.generatedAt, periods: use };
}

async function tioga() {
  const html = await get('https://www.nps.gov/yose/planyourvisit/conditions.htm', 'text');
  const text = strip(html);
  const i = text.search(/Tioga Road/i);
  return i >= 0 ? text.slice(i, i + 360) : 'Could not find Tioga Road on the NPS conditions page. Check it directly.';
}

async function caltrans(route) {
  const html = await get(`https://roads.dot.ca.gov/roadscell.php?roadnumber=${route}`, 'text');
  const text = strip(html);
  const i = text.search(new RegExp(`SR ${route}|US ${route}|${route}\\b`, 'i'));
  return text.slice(Math.max(0, i), Math.max(0, i) + 700);
}

const result = { retrieved: new Date().toISOString(), forecasts: [], tioga: null, roads: {}, errors: [] };
for (const p of PLACES) {
  try { result.forecasts.push(await forecast(p)); } catch (e) { result.errors.push(`${p[0]}: ${e.message}`); }
}
try { result.tioga = await tioga(); } catch (e) { result.errors.push('NPS: ' + e.message); }
for (const r of ['120', '395', '108']) {
  try { result.roads[r] = await caltrans(r); } catch (e) { result.errors.push(`Caltrans ${r}: ${e.message}`); }
}

await writeFile(out, `// Generated by scripts/update-conditions.mjs. Do not edit by hand.\nexport const conditions = ${JSON.stringify(result, null, 2)};\n`);
console.log(`Wrote conditions.js: ${result.forecasts.length} forecasts (${result.forecasts.filter((f) => f.onTrip).length} reach the trip dates), Tioga: ${result.tioga ? 'ok' : 'missing'}, roads: ${Object.keys(result.roads).join(', ')}`);
if (result.errors.length) console.log('Problems:\n  ' + result.errors.join('\n  '));
