// Pre-render the lit terrain so the app never rasterizes huge contour SVGs at
// runtime. For each region (route, eastside) and theme (light, dark, night):
//   public/img/topo/relief-<region>-<theme>.webp
// and the small data module the app uses instead of the 590 KB contour JSON:
//   src/art/terrain-data.ts  (sizes, bounds, stops, elevations, levels)
//
// Source contours: art/topo/*.json (from scripts/topo.mjs; not shipped).
// Usage: npm run relief     (needs the preinstalled Playwright Chromium)
//        node scripts/relief.mjs --data-only
//
// The relief is Tanaka "illuminated contours": each elevation band is filled
// from a hypsometric ramp, and copies shifted toward/away from the sun leave a
// lit sliver on slopes facing it and a shaded sliver on the others.
//   light  sunrise from the east (top of the map); calm: half the offset and
//          sliver strength of the prototype, hairline index contours carry it
//   dark   evening sun from the west (bottom); dimmer slivers, fills at ~60%
//   night  red-shifted and dim, for night vision
// Mono Lake is drawn as water: inside the 1,900 m surface, outside 1,960 m.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const load = (n) => JSON.parse(readFileSync(join(root, 'art/topo', n + '.json'), 'utf8'));
const route = load('route');
const east = load('eastside');

// ---------------------------------------------------------------------------
// Data module

const f2 = (n) => Math.round(n * 100) / 100;

// Raster resolution (px per map unit) and tile grid [cols, rows].
const SCALE = { route: { light: 5, dark: 5, night: 2.5 }, eastside: { light: 6, dark: 6, night: 4 } };
const GRID = { route: { light: [1, 3], dark: [1, 3], night: [1, 1] }, eastside: { light: [2, 2], dark: [2, 2], night: [1, 1] } };
const OVERLAP = 2; // px on each inner edge, so tile seams never show
const SIZE = { route: [route.width, route.height], eastside: [east.width, east.height] };
/** Pixel rects (and unit rects) of each tile. */
function tileRects(name, theme) {
  const k = SCALE[name][theme];
  const [uw, uh] = SIZE[name];
  const W = Math.round(uw * k), H = Math.round(uh * k);
  const [cols, rows] = GRID[name][theme];
  const out = [];
  for (let r = 0; r < rows; r++)
    for (let c = 0; c < cols; c++) {
      const x0 = Math.max(0, Math.round((c * W) / cols) - (c ? OVERLAP : 0));
      const x1 = Math.min(W, Math.round(((c + 1) * W) / cols) + (c < cols - 1 ? OVERLAP : 0));
      const y0 = Math.max(0, Math.round((r * H) / rows) - (r ? OVERLAP : 0));
      const y1 = Math.min(H, Math.round(((r + 1) * H) / rows) + (r < rows - 1 ? OVERLAP : 0));
      out.push({ px: [x0, y0, x1 - x0, y1 - y0], i: out.length, W, H, k });
    }
  return out;
}
const r3 = (n) => Math.round(n * 1000) / 1000;
function tilesFor() {
  const o = {};
  for (const name of ['route', 'eastside']) {
    o[name] = {};
    for (const theme of ['light', 'dark', 'night']) {
      o[name][theme] = tileRects(name, theme).map((t) => {
        const [x, y, w, h] = t.px;
        return { f: `relief-${name}-${theme}-${t.i}.webp`, x: r3(x / t.k), y: r3(y / t.k), w: r3(w / t.k), h: r3(h / t.k) };
      });
    }
  }
  return o;
}
function regionData(T) {
  return {
    width: T.width,
    height: T.height,
    bounds: T.bounds,
    levels: T.levels,
    stops: Object.fromEntries(Object.entries(T.stops).map(([k, [x, y]]) => [k, [f2(x), f2(y)]])),
    stopElevation: T.stopElevation,
  };
}
// eastside → route: both are linear east-up projections of lat/lon.
//   route.x = (Nr - lat) / (Nr - Sr) * Wr ;  lat = Ne - ex/We * (Ne - Se)
const R = route.bounds, E = east.bounds;
const ax = (route.width / (R.north - R.south)) * ((E.north - E.south) / east.width);
const bx = (route.width / (R.north - R.south)) * (R.north - E.north);
const ay = (route.height / (R.east - R.west)) * ((E.east - E.west) / east.height);
const by = (route.height / (R.east - R.west)) * (R.east - E.east);
const E2R = [ax, 0, 0, ay, bx, by].map((n) => Math.round(n * 1e5) / 1e5);

const dataTs = `// Generated by scripts/relief.mjs from art/topo/*.json. Do not edit.
// Coordinates are map units, EAST IS UP: x runs north→south across the
// width, y runs east→west down the height (the drive goes bottom → top).
export const REGIONS = ${JSON.stringify({ route: regionData(route), eastside: regionData(east) }, null, 2)} as const;

/** SVG matrix(a b c d e f) mapping eastside units into route units. */
export const EAST_TO_ROUTE = ${JSON.stringify(E2R)} as const;

/** Relief raster resolution (pixels per map unit) per region and theme. */
export const RELIEF_SCALE = ${JSON.stringify(SCALE)} as const;

/** Relief tiles per region and theme, in map units (they overlap by 2 px). */
export const RELIEF_TILES = ${JSON.stringify(tilesFor(), null, 0)} as const;
`;
writeFileSync(join(root, 'src/art/terrain-data.ts'), dataTs);
console.log('wrote src/art/terrain-data.ts');
if (process.argv.includes('--data-only')) process.exit(0);

