const slim = (d) => d.replace(/(\d+)\.(\d)/g, (m, a, b) => (b === '0' ? a : `${a}.${b}`));

function reliefSVG(T, theme, scale, name) {
  const P = PAL[theme];
  const W = Math.round(T.width * scale), H = Math.round(T.height * scale);
  // Hairline widths are tuned in map units at the original resolution, so
  // they read the same whatever the raster scale.
  const ref = name === 'route' ? 2.5 : 4;
  const levels = T.layers.map((l) => l.level);
  const lo = Math.min(...levels.filter((l) => l > 0)), hi = Math.max(...levels);
  const sy = P.sun * P.shift;
  const idxEvery = name === 'route' ? 600 : 300;
  const isIndex = (lv) => lv > 0 && (lv - (name === 'route' ? 100 : 1900)) % idxEvery === 0;
  const defs = [], body = [], index = [];
  // The lake basin, in eastside units: the 1,900–1,960 m band inside this
  // ellipse is water (outside it, that band is dry valley floor).
  const monoC = [121, 150];

  T.layers.forEach((l, i) => {
    const id = `L${i}`;
    defs.push(`<path id="${id}" d="${slim(l.d)}"/>`);
    const t = Math.max(0, (l.level - lo) / (hi - lo || 1));
    const fill = ramp(P.ramp, t);
    const a = (P.litMin + (P.litMax - P.litMin) * Math.pow(t, 1.2)).toFixed(3);
    const lit = `rgba(${P.lit.join(',')},${a})`;
    if (name === 'route' && l.level === 0) {
      // Bay shoreline: land above sea level over water.
      body.push(`<use href="#${id}" fill="${fill}"/>`);
      return;
    }
    if (name === 'eastside' && l.level === 1900) {
      // The lowest surface: water inside the lake basin, land elsewhere.
      body.push(`<use href="#${id}" fill="${fill}"/>`);
      body.push(`<g clip-path="url(#mono)"><use href="#${id}" fill="${P.water}"/></g>`);
      return;
    }
    body.push(
      `<use href="#${id}" transform="translate(0 ${sy})" fill="${lit}"/>` +
        `<use href="#${id}" transform="translate(0 ${-sy})" fill="${P.shade}"/>` +
        `<use href="#${id}" fill="${fill}"/>`,
    );
    if (name === 'route' && l.level === 1900) {
      // Mono Lake from the finer eastside contours, registered by affine.
      const e19 = east.layers.find((x) => x.level === 1900).d, e196 = east.layers.find((x) => x.level === 1960).d;
      // Water = inside 1,900 m and outside 1,960 m (a mask, so the relief
      // around the lake keeps its slivers).
      defs.push(`<mask id="lakeR" maskUnits="userSpaceOnUse" x="0" y="0" width="${T.width}" height="${T.height}"><g transform="matrix(${E2R.join(' ')})"><path d="${slim(e19)}" fill="#fff"/><path d="${slim(e196)}" fill="#000"/></g></mask>`);
      body.push(`<g clip-path="url(#monoR)"><rect x="0" y="0" width="${T.width}" height="${T.height}" fill="${P.water}" mask="url(#lakeR)"/></g>`);
    }
    if (isIndex(l.level)) index.push(`<use href="#${id}" fill="none" stroke="${P.index}" stroke-width="${(P.indexW / ref).toFixed(3)}"/>`);
  });
  // Lake shore line on the eastside map (the 1,960 m contour, inside the basin).
  if (name === 'eastside') {
    const i196 = T.layers.findIndex((x) => x.level === 1960);
    index.push(`<g clip-path="url(#mono)"><use href="#L${i196}" fill="none" stroke="${P.shore}" stroke-width="${(1.1 / ref).toFixed(3)}"/></g>`);
  }

  const base = name === 'route' ? P.water : ramp(P.ramp, 0);
  const [mx, my] = monoC;
  const rM = [mx * E2R[0] + E2R[4], my * E2R[3] + E2R[5]];
  return {
    W,
    H,
    svg: `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${T.width} ${T.height}">
<defs>${defs.join('')}
<clipPath id="mono"><ellipse cx="${mx}" cy="${my}" rx="72" ry="63"/></clipPath>
<clipPath id="monoR"><ellipse cx="${rM[0].toFixed(1)}" cy="${rM[1].toFixed(1)}" rx="${(72 * E2R[0]).toFixed(1)}" ry="${(63 * E2R[3]).toFixed(1)}"/></clipPath>
</defs>
<rect x="-5" y="-5" width="${T.width + 10}" height="${T.height + 10}" fill="${base}"/>
${body.join('\n')}
${index.join('\n')}
</svg>`,
  };
}

// ---------------------------------------------------------------------------
// Rasterize in Chromium (SVG → canvas → WebP)

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/opt/node22/lib/node_modules/playwright/index.mjs');
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><html><body></body></html>');
const outDir = join(root, 'public/img/topo');
mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (/^relief-.*\.webp$/.test(f)) unlinkSync(join(outDir, f));
const Q = { light: 0.78, dark: 0.8, night: 0.8 };

for (const [name, T] of [['route', route], ['eastside', east]]) {
  for (const theme of ['light', 'dark', 'night']) {
    const k = SCALE[name][theme];
    const { svg, W, H } = reliefSVG(T, theme, k, name);
    const tiles = tileRects(name, theme).map((t) => t.px);
    const out = await page.evaluate(
      async ({ svg, W, H, q, tiles }) => {
        const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
        const img = new Image();
        img.src = url;
        await img.decode();
        const c = document.createElement('canvas');
        c.width = W;
        c.height = H;
        c.getContext('2d').drawImage(img, 0, 0, W, H);
        URL.revokeObjectURL(url);
        return tiles.map(([x, y, w, h]) => {
          const t = document.createElement('canvas');
          t.width = w;
          t.height = h;
          t.getContext('2d').drawImage(c, x, y, w, h, 0, 0, w, h);
          return t.toDataURL('image/webp', q).split(',')[1];
        });
      },
      { svg, W, H, q: Q[theme], tiles },
    );
    out.forEach((b64, i) => {
      const buf = Buffer.from(b64, 'base64');
      writeFileSync(join(outDir, `relief-${name}-${theme}-${i}.webp`), buf);
      console.log(`wrote relief-${name}-${theme}-${i}.webp  ${tiles[i][2]}×${tiles[i][3]}  ${(buf.length / 1024).toFixed(0)} KB`);
    });
  }
}
await browser.close();
